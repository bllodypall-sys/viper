-- Storage del muro: los propietarios suben; lectura solo si la publicación es visible.
drop policy if exists community_images_owner_upload on storage.objects;
create policy community_images_owner_upload on storage.objects for insert to authenticated
with check (bucket_id='community-images' and (storage.foldername(name))[1]=auth.uid()::text);
drop policy if exists community_images_visible_read on storage.objects;
create policy community_images_visible_read on storage.objects for select to authenticated using (
  bucket_id='community-images' and exists (
    select 1 from public.posts p where p.image_path=storage.objects.name
    and public.can_view_social_content(p.user_id)
  )
);
drop policy if exists community_images_owner_delete on storage.objects;
create policy community_images_owner_delete on storage.objects for delete to authenticated
using (bucket_id='community-images' and (storage.foldername(name))[1]=auth.uid()::text);

