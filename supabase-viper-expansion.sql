-- Temporadas: el XP histórico de profiles no se modifica.
create table if not exists public.seasons (
  id bigint generated by default as identity primary key,
  name text not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status text not null default 'scheduled' check (status in ('scheduled','active','finished')),
  created_at timestamptz not null default now(),
  constraint seasons_dates check (ends_at > starts_at)
);
create unique index if not exists seasons_one_active_idx
  on public.seasons(status) where status='active';

create table if not exists public.season_scores (
  season_id bigint not null references public.seasons(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  xp integer not null default 0 check (xp >= 0),
  updated_at timestamptz not null default now(),
  primary key (season_id,user_id)
);
create index if not exists season_scores_rank_idx on public.season_scores(season_id,xp desc);

-- Retos semanales: el catálogo lo administra el backend; el usuario solo consulta
-- retos y su propio avance.
create table if not exists public.challenges (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  metric text not null check (metric in ('training_days','xp','streak')),
  target integer not null check (target > 0),
  reward_xp integer not null default 0 check (reward_xp >= 0),
  starts_on date not null,
  ends_on date not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint challenges_dates check (ends_on >= starts_on)
);
create table if not exists public.challenge_progress (
  challenge_id bigint not null references public.challenges(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  progress integer not null default 0 check (progress >= 0),
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (challenge_id,user_id)
);

-- Muro social y comentarios.
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null default '' check (length(body) <= 1500),
  image_path text,
  post_type text not null default 'training' check (post_type in ('training','achievement','photo')),
  created_at timestamptz not null default now(),
  constraint posts_content check (length(trim(body)) > 0 or image_path is not null)
);
create index if not exists posts_created_idx on public.posts(created_at desc);
create table if not exists public.post_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (length(trim(body)) between 1 and 800),
  created_at timestamptz not null default now()
);
create index if not exists post_comments_post_idx on public.post_comments(post_id,created_at);

-- Registro de ejercicios. Un registro representa un ejercicio dentro de una sesión.
create table if not exists public.exercise_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  exercise_name text not null check (length(trim(exercise_name)) between 1 and 80),
  weight_kg numeric(7,2) not null default 0 check (weight_kg >= 0),
  sets integer not null check (sets between 1 and 50),
  reps integer not null check (reps between 1 and 500),
  performed_on date not null default (now() at time zone 'America/Lima')::date,
  notes text check (length(notes) <= 500),
  created_at timestamptz not null default now()
);
create index if not exists exercise_logs_user_date_idx on public.exercise_logs(user_id,performed_on desc);
create table if not exists public.personal_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  exercise_name text not null,
  weight_kg numeric(7,2) not null check (weight_kg > 0),
  achieved_on date not null default (now() at time zone 'America/Lima')::date,
  exercise_log_id bigint references public.exercise_logs(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists personal_records_user_idx on public.personal_records(user_id,achieved_on desc);

-- Notificaciones: solo el destinatario puede leer/marcar como leídas.
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  kind text not null check (kind in ('message','friend_request','challenge','rank_up','comment','like','system')),
  title text not null check (length(title) <= 120),
  body text not null default '' check (length(body) <= 500),
  target_type text,
  target_id text,
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists notifications_user_unread_idx on public.notifications(user_id,created_at desc) where read_at is null;

-- Calendario de actividad: los check-ins existentes siguen siendo la fuente de verdad
-- para días de gimnasio; esta tabla permite registrar descanso y objetivos.
create table if not exists public.activity_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  activity_date date not null,
  kind text not null check (kind in ('training','rest','goal')),
  title text not null check (length(title) <= 100),
  details text check (length(details) <= 300),
  created_at timestamptz not null default now(),
  unique(user_id,activity_date,kind,title)
);
create index if not exists activity_events_user_date_idx on public.activity_events(user_id,activity_date desc);

-- Bloqueos y reportes.
create table if not exists public.user_blocks (
  blocker_id uuid not null references auth.users(id) on delete cascade,
  blocked_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id,blocked_id),
  constraint user_blocks_no_self check (blocker_id <> blocked_id)
);
create table if not exists public.content_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reported_user_id uuid references auth.users(id) on delete set null,
  content_type text not null check (content_type in ('user','post','comment','message')),
  content_id text,
  reason text not null check (length(trim(reason)) between 3 and 500),
  status text not null default 'open' check (status in ('open','reviewing','closed')),
  created_at timestamptz not null default now()
);

-- Función segura para comprobar bloqueos en ambos sentidos sin depender
-- de las políticas RLS de user_blocks (evita que un bloqueo del autor se oculte).
create or replace function public.is_blocked_between(user_a uuid, user_b uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $function$
  select exists (
    select 1 from public.user_blocks
    where (blocker_id=user_a and blocked_id=user_b)
       or (blocker_id=user_b and blocked_id=user_a)
  );
$function$;
revoke all on function public.is_blocked_between(uuid,uuid) from public, anon;

grant execute on function public.is_blocked_between(uuid,uuid) to authenticated;

-- El muro solo muestra publicaciones propias o de amistades aceptadas.
-- También oculta contenido si cualquiera de las dos personas bloqueó a la otra.
create or replace function public.can_view_social_content(author_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $social$
  select
    auth.uid() is not null
    and (
      author_id = auth.uid()
      or exists (
        select 1
        from public.friendships f
        where f.estado = 'aceptada'
          and (
            (f.solicitante = auth.uid() and f.destinatario = author_id)
            or
            (f.destinatario = auth.uid() and f.solicitante = author_id)
          )
      )
    )
    and not public.is_blocked_between(auth.uid(), author_id);
$social$;
revoke all on function public.can_view_social_content(uuid) from public, anon;
grant execute on function public.can_view_social_content(uuid) to authenticated;

