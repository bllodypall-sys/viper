-- VIPER BOXEO: historial de sesiones sincronizado por cuenta.
-- Migración aditiva: no modifica perfiles, XP, check-ins ni registros existentes.
create table if not exists public.boxing_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  client_id text not null check (length(client_id) between 1 and 100),
  session_at timestamptz not null default now(),
  kind text not null check (length(trim(kind)) between 1 and 30),
  rounds_completed integer not null check (rounds_completed between 0 and 20),
  rounds_planned integer not null check (rounds_planned between 1 and 20),
  round_minutes integer not null check (round_minutes between 1 and 10),
  rest_seconds integer not null check (rest_seconds between 15 and 300),
  warmup_minutes integer not null default 0 check (warmup_minutes between 0 and 30),
  elapsed_seconds integer not null check (elapsed_seconds between 0 and 86400),
  created_at timestamptz not null default now(),
  constraint boxing_sessions_client_unique unique(user_id,client_id)
);
create index if not exists boxing_sessions_user_date_idx
  on public.boxing_sessions(user_id,session_at desc);
alter table public.boxing_sessions enable row level security;
drop policy if exists boxing_sessions_owner_all on public.boxing_sessions;
create policy boxing_sessions_owner_all on public.boxing_sessions
  for all to authenticated
  using (user_id=auth.uid())
  with check (user_id=auth.uid());
grant select,insert,delete on public.boxing_sessions to authenticated;
grant usage,select on sequence public.boxing_sessions_id_seq to authenticated;
