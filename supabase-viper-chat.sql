insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('avatars','avatars',true,8388608,array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public=true, file_size_limit=8388608, allowed_mime_types=array['image/jpeg','image/png','image/webp'];

insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('chat-images','chat-images',false,8388608,array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public=false, file_size_limit=8388608, allowed_mime_types=array['image/jpeg','image/png','image/webp'];

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('text','image','progress')),
  content text,
  media_path text,
  progress_xp integer,
  progress_rank text,
  created_at timestamptz not null default now(),
  constraint messages_no_self check (sender_id <> recipient_id),
  constraint messages_payload check (
    (kind='text' and length(trim(coalesce(content,''))) between 1 and 1500 and media_path is null)
    or (kind='image' and media_path is not null and content is null)
    or (kind='progress' and progress_xp is not null and progress_xp >= 0 and progress_rank is not null)
  )
);

create index if not exists messages_sender_recipient_created_idx
on public.messages(sender_id,recipient_id,created_at);
create index if not exists messages_recipient_sender_created_idx
on public.messages(recipient_id,sender_id,created_at);

alter table public.messages enable row level security;
drop policy if exists "messages_read_friends" on public.messages;
create policy "messages_read_friends" on public.messages
for select to authenticated
using (
  (sender_id=auth.uid() or recipient_id=auth.uid())
  and exists (
    select 1 from public.friendships f
    where f.estado='aceptada'
      and ((f.solicitante=messages.sender_id and f.destinatario=messages.recipient_id)
        or (f.solicitante=messages.recipient_id and f.destinatario=messages.sender_id))
  )
);
drop policy if exists "messages_send_friends" on public.messages;
create policy "messages_send_friends" on public.messages
for insert to authenticated
with check (
  sender_id=auth.uid()
  and recipient_id<>auth.uid()
  and exists (
    select 1 from public.friendships f
    where f.estado='aceptada'
      and ((f.solicitante=auth.uid() and f.destinatario=messages.recipient_id)
        or (f.destinatario=auth.uid() and f.solicitante=messages.recipient_id))
  )
);

-- Permisos explícitos de tabla y secuencia para el cliente autenticado.
grant select, insert on public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

-- El bucket avatars es público: no necesita una política SELECT en storage.objects.
-- Evitamos permitir el listado de todos los archivos del bucket.
drop policy if exists "avatars_public_read" on storage.objects;

drop policy if exists "avatars_owner_upload" on storage.objects;
create policy "avatars_owner_upload" on storage.objects
for insert to authenticated
with check (bucket_id='avatars' and (storage.foldername(name))[1]=auth.uid()::text);
drop policy if exists "avatars_owner_update" on storage.objects;
create policy "avatars_owner_update" on storage.objects
for update to authenticated
using (bucket_id='avatars' and (storage.foldername(name))[1]=auth.uid()::text)
with check (bucket_id='avatars' and (storage.foldername(name))[1]=auth.uid()::text);
drop policy if exists "avatars_owner_delete" on storage.objects;
create policy "avatars_owner_delete" on storage.objects
for delete to authenticated
using (bucket_id='avatars' and (storage.foldername(name))[1]=auth.uid()::text);

drop policy if exists "chat_images_owner_upload" on storage.objects;
create policy "chat_images_owner_upload" on storage.objects
for insert to authenticated
with check (bucket_id='chat-images' and (storage.foldername(name))[1]=auth.uid()::text);
drop policy if exists "chat_images_friends_read" on storage.objects;
create policy "chat_images_friends_read" on storage.objects
for select to authenticated
using (
  bucket_id='chat-images'
  and exists (
    select 1 from public.messages m
    where m.media_path=storage.objects.name
      and (m.sender_id=auth.uid() or m.recipient_id=auth.uid())
  )
);
drop policy if exists "chat_images_owner_delete" on storage.objects;
create policy "chat_images_owner_delete" on storage.objects
for delete to authenticated
using (bucket_id='chat-images' and (storage.foldername(name))[1]=auth.uid()::text);

